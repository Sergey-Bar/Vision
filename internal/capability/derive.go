// 6. PartitionHorizon
// ---------------------------------------------------------------------------

// DefaultPartitionHorizonMonths is how far ahead a partitioned table must reach.
//
// Eighteen, not twelve. A year is the interval most of these tables are reviewed on,
// so a horizon of twelve months is satisfied by the partitions that were correct when
// the table was created and reports a table as covered while it is three months from
// failing.
const DefaultPartitionHorizonMonths = 18

// DerivePartitionHorizon asserts that every RANGE-partitioned parent has partitions
// reaching at least `months` past `today`.
//
// It reads the migrations rather than the catalogue, because the gate has to run
// without a database: `internal/treestate`, `internal/deadexport`,
// `internal/predicatecov` and `internal/statuscheck` are all static for that reason,
// and a gate that needs Postgres is a gate nobody runs on the machine where the tree
// is wrong.
//
// The DEFAULT partitions migration 0015 added are deliberately NOT counted. They are
// why ingest does not fail on the boundary date, and they are also why the failure is
// invisible when it arrives: every row lands in one unpartitioned relation, so nothing
// prunes, index growth is unbounded, and every incident-window query becomes a
// sequential scan. A DEFAULT partition converts a loud failure into a slow one, and a
// slow one is found by a customer rather than by a gate.
func DerivePartitionHorizon(root string, today time.Time, months int) (Table, error) {
	t := Table{
		Name: "PartitionHorizon",
		Asserts: fmt.Sprintf("every RANGE-partitioned table has partitions covering at least %d "+
			"months from today. The DEFAULT partitions do not count: they make ingest succeed "+
			"into one unpartitioned relation, so the failure arrives as a slow query rather than "+
			"as an error", months),
	}
	parents, err := rangePartitionParents(root)
	if err != nil {
		return t, err
	}
	through, err := partitionCoverage(root)
	if err != nil {
		return t, err
	}
	want := addMonths(today, months)
	for _, parent := range parents {
		item := Item{Name: parent}
		end, covered := through[parent]
		switch {
		case !covered:
			item.Evidence = fmt.Sprintf("a partition covering through %s", want.Format("2006-01-02"))
		case end.Before(want):
			item.Evidence = fmt.Sprintf("partitions reach %s, and %d months from today is %s",
				end.Format("2006-01-02"), months, want.Format("2006-01-02"))
		default:
			item.Covered = true
			item.Evidence = "partitions reach " + end.Format("2006-01-02")
		}
		t.Items = append(t.Items, item)
	}
	sortItems(t.Items)
	return t, nil
}

var (
	// partitionByRange matches the declaration that makes a table partitioned.
	//
	// It is matched against the WHOLE file rather than against a `;`-delimited
	// statement, because `PARTITION BY RANGE (...)` is a trailing clause of the
	// CREATE TABLE: it sits after the column list's closing paren, and the column list
	// contains no semicolons. Splitting first therefore loses exactly the clause being
	// looked for. That was the bug: the table derived zero parents and reported nothing,
	// which looks identical to a healthy tree.
	partitionByRange = regexp.MustCompile(`(?i)CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-z_][a-z0-9_]*)\s*\((?:[^;]*?)\)\s*PARTITION\s+BY\s+RANGE\s*\(`)
	// partitionOf matches `CREATE TABLE <child> PARTITION OF <parent>`.
	partitionOf = regexp.MustCompile(`(?i)CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?([a-z_][a-z0-9_]*)\s+PARTITION\s+OF\s+([a-z_][a-z0-9_]*)`)
	// forValues matches the bounds of a RANGE partition.
	forValues = regexp.MustCompile(`(?i)FOR\s+VALUES\s+FROM\s+\('?([0-9]{4}-[0-9]{2}-[0-9]{2}[^')]*)'?\)\s+TO\s+\('?([0-9]{4}-[0-9]{2}-[0-9]{2}[^')]*)'?\)`)
)

func rangePartitionParents(root string) ([]string, error) {
	entries, err := os.ReadDir(filepath.Join(root, "migrations"))
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		raw, readErr := os.ReadFile(filepath.Join(root, "migrations", e.Name()))
		if readErr != nil {
			return nil, readErr
		}
		for _, m := range partitionByRange.FindAllStringSubmatch(string(raw), -1) {
			seen[strings.ToLower(m[1])] = true
		}
	}
	out := make([]string, 0, len(seen))
	for name := range seen {
		out = append(out, name)
	}
	sort.Strings(out)
	return out, nil
}

// partitionCoverage returns the furthest upper bound declared for each parent.
//
// A parent whose only partition is DEFAULT has no bounds and is absent from the map,
// and absence is a failure - which is the right answer for a parent created today with no
// partitions at all.
func partitionCoverage(root string) (map[string]time.Time, error) {
	entries, err := os.ReadDir(filepath.Join(root, "migrations"))
	if err != nil {
		return nil, err
	}
	through := map[string]time.Time{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		raw, readErr := os.ReadFile(filepath.Join(root, "migrations", e.Name()))
		if readErr != nil {
			return nil, readErr
		}
		text := string(raw)
		for _, m := range partitionOf.FindAllStringSubmatchIndex(text, -1) {
			// The bounds may be on the following line, so the search runs over the text
			// that begins at this CREATE rather than on the matched line alone.
			bounds := forValues.FindStringSubmatch(text[m[0]:])
			if bounds == nil {
				continue
			}
			upper, parseErr := parseStamp(bounds[2])
			if parseErr != nil {
				continue
			}
			parent := strings.ToLower(text[m[4]:m[5]])
			if prev, seen := through[parent]; !seen || upper.After(prev) {
				through[parent] = upper
			}
		}
	}
	return through, nil
}

// parseStamp reads a partition bound, which every migration writes as an RFC 3339
// instant with a `Z`.
//
// The `Z` is trimmed rather than the offset being honoured, because partition bounds are
// compared against each other and against `today` in UTC - a bound written as local time
// is a different month boundary, and the migrations here all write UTC.
func parseStamp(s string) (time.Time, error) {
	t := strings.TrimSuffix(strings.TrimSpace(s), "Z")
	return time.Parse("2006-01-02T15:04:05", t)
}

// addMonths adds whole months, clamping the day rather than overflowing.
//
// `today.AddDate(0, months, 0)` on 31 January gives 2 or 3 March, which would make the
// horizon a function of the day the gate happened to run on - a table that passed on
// the 30th would fail on the 31st with no change to the tree.
func addMonths(t time.Time, months int) time.Time {
	t = t.UTC()
	year, month, day := t.Date()
	targetMonth := time.Month(int(month) + months)
	targetYear := year
	for targetMonth > time.December {
		targetMonth -= 12
		targetYear++
	}
	for targetMonth < time.January {
		targetMonth += 12
		targetYear--
	}
	last := daysInMonth(targetYear, targetMonth)
	if day > last {
		day = last
	}
	return time.Date(targetYear, targetMonth, day, t.Hour(), t.Minute(), t.Second(), 0, time.UTC)
}

func daysInMonth(year int, month time.Month) int {
	return time.Date(year, month+1, 0, 0, 0, 0, 0, time.UTC).Day()
}

