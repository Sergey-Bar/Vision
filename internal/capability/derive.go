// 7. SiteScopedWriteCanaries
// ---------------------------------------------------------------------------

// DeriveSiteScopedWriteCanaries asserts that every site-bearing table is covered by a
// write canary in `internal/rlsrole`.
//
// The table list is derived from `migrations/` with the same two rules
// `internal/rlsrole` uses - a `CREATE TABLE` whose body declares a `site_id` column -
// so this gate and the canaries agree on what "site-scoped" means. Two different
// notions of that phrase is one of the ways a readiness check stops meaning anything,
// and `site_isolation_test.go` says so in its own comment.
//
// The canary list is read out of `write_canary_test.go` rather than imported, because
// it is a test fixture: there is no non-test symbol that enumerates it.
func DeriveSiteScopedWriteCanaries(root string) (Table, error) {
	t := Table{
		Name: "SiteScopedWriteCanaries",
		Asserts: "every site-bearing table has a write canary asserting its writes are scoped " +
			"to the caller's sites. A read canary passes on an unprotected table - a SELECT " +
			"returns no rows either way - so the uncovered ones are exactly the ones nothing " +
			"has ever tried to write across",
	}
	tables, err := SiteScopedTables(root)
	if err != nil {
		return t, err
	}
	canaries, err := writeCanaryTables(root)
	if err != nil {
		return t, err
	}
	for _, name := range tables {
		item := Item{Name: name}
		if file, ok := canaries[name]; ok {
			item.Covered = true
			item.Evidence = file
		} else {
			item.Evidence = "a writeCanary entry in internal/rlsrole"
		}
		t.Items = append(t.Items, item)
	}
	sortItems(t.Items)
	return t, nil
}

// The two rules that decide a table is site-bearing. They are copied from
// `internal/rlsrole/site_isolation_test.go` rather than shared, because that file is a
// `_test.go` in another package and a shared helper across two packages means one of
// them importing the other.
//
// The duplication is stated rather than hidden, and the guard is the derivation
// itself: if either regex drifts, this table and the canaries disagree, and both say so
// in their own output rather than one silently covering fewer tables than the other.
var (
	createTableBody = regexp.MustCompile(`(?is)create\s+table\s+([a-z_][a-z0-9_]*)\s*\((.*?)\n\);`)
	siteIDColumn    = regexp.MustCompile(`(?im)^\s*site_id\s+[a-z]`)
)

// SiteScopedTables derives every site-bearing table from the migrations.
func SiteScopedTables(root string) ([]string, error) {
	entries, err := os.ReadDir(filepath.Join(root, "migrations"))
	if err != nil {
		return nil, err
	}
	seen := map[string]bool{}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".sql") {
			continue
		}
		raw, readErr := os.ReadFile(filepath.Join(root, "migrations", e.Name()))
		if readErr != nil {
			return nil, readErr
		}
		for _, m := range createTableBody.FindAllStringSubmatch(string(raw), -1) {
			// Partitioned parents are excluded: RLS on a partitioned table applies to
			// its partitions, and a canary against the parent would be a canary against
			// a relation that holds no rows.
			if strings.Contains(strings.ToUpper(m[1]), "PARTITION") {
				continue
			}
			if siteIDColumn.MatchString(m[2]) {
				seen[strings.ToLower(m[1])] = true
			}
		}
	}
	out := make([]string, 0, len(seen))
	for name := range seen {
		out = append(out, name)
	}
	sort.Strings(out)
	return out, nil
}

// canaryTableRe reads the `table:` field of each writeCanary entry.
var canaryTableRe = regexp.MustCompile(`table:\s*"([a-z_][a-z0-9_]*)"`)

func writeCanaryTables(root string) (map[string]string, error) {
	path := filepath.Join(root, "internal", "rlsrole", "write_canary_test.go")
	raw, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			// The file not existing is not a derivation failure. It means no table has
			// a canary, which every item below then says in its own evidence field.
			return map[string]string{}, nil
		}
		return nil, err
	}
	out := map[string]string{}
	for _, m := range canaryTableRe.FindAllStringSubmatch(string(raw), -1) {
		out[m[1]] = "internal/rlsrole/write_canary_test.go"
	}
	return out, nil
}

