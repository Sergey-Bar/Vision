package capability

// The seven derivations. Every list in this file is derived from the tree, never
// written by hand, and the reason is the failure this repository has already paid
// for twice: `internal/README.md` traps 14 and 15 are both a document whose
// hand-maintained count was wrong, and both are why `internal/statuscheck` and
// `internal/sqlguard` derive instead.
//
// Each derivation is different because the facts are different in kind:
//
//	DispatchExecutors       a Go switch in internal/dispatch is the registration
//	QueueEndpoints          two searches in two trees: a producer and a worker
//	MetricProducers         the const block is the list; the tree is the producer
//	CapabilityEnforcement   identity owns the vocabulary; the tree is the gate
//	ContractRouting         the document is the list; the mux is the implementation
//	PartitionHorizon        migrations/ is the list; the wall clock is the horizon
//	SiteScopedWriteCanaries migrations/ is the list; the rlsrole file is the canaries

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"
)

// scanRoots are the trees a derivation reads. `poc` is a second Go module and is
// pruned by the walk's skip set, exactly as `internal/deadexport` does it.
//
// The second root matters: a producer is frequently in `cmd/security-core` rather
// than in `internal/`, and a gate that only walked `internal` would report the VLM
// queue as having no worker while `main.go` registers one.
var scanRoots = []string{"internal", "cmd"}

// skipDirs are directory names pruned anywhere in a walk.
//
// `.kilo` holds other checkouts of this repository, so a match inside one is not a
// match in the tree being gated.
var skipDirs = map[string]bool{
	".git": true, ".kilo": true, "poc": true, "node_modules": true,
	"__pycache__": true, "dist": true, "testdata": true,
}

// Corpus is every non-test, non-generated .go file under the scan roots.
//
// Non-test, because a producer in a test file is not a producer: that is the
// entire defect. Non-generated, because `internal/contracts` embeds copies of the
// published schemas and one of them names every dispatch type, so including them
// would make this gate pass on a file nothing executes.
type Corpus struct {
	root   string
	files  []string // module-relative, slash-separated, sorted
	byFile map[string]string
}

// LoadCorpus reads the tree's production Go source.
func LoadCorpus(root string) (*Corpus, error) {
	c := &Corpus{root: root, byFile: map[string]string{}}
	for _, dir := range scanRoots {
		base := filepath.Join(root, dir)
		err := filepath.WalkDir(base, func(path string, d os.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() {
				if skipDirs[d.Name()] {
					return filepath.SkipDir
				}
				return nil
			}
			if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
				return nil
			}
			raw, readErr := os.ReadFile(path)
			if readErr != nil {
				return readErr
			}
			if isGenerated(raw) {
				return nil
			}
			rel, relErr := filepath.Rel(root, path)
			if relErr != nil {
				rel = path
			}
			rel = filepath.ToSlash(rel)
			c.files = append(c.files, rel)
			c.byFile[rel] = string(raw)
			return nil
		})
		if err != nil {
			return nil, err
		}
	}
	sort.Strings(c.files)
	return c, nil
}

// Files is the module-relative list the corpus read, so a gate can say how much
// it looked at rather than passing over the size of the tree in silence.
func (c *Corpus) Files() []string { return append([]string(nil), c.files...) }

// isGenerated reports whether a file carries the generated marker.
//
// The convention is the first line of the file, before the package clause, so a
// reader sees it before anything else. A substring search across the whole file
// would exclude a hand-written file that mentions the phrase in a comment, which
// is a false negative in the direction that does not get caught.
func isGenerated(raw []byte) bool {
	head := string(raw)
	if len(head) > 4096 {
		head = head[:4096]
	}
	for _, line := range strings.Split(head, "\n") {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "package ") {
			return false
		}
		if !strings.HasPrefix(trimmed, "//") {
			continue
		}
		c := strings.TrimSpace(strings.TrimPrefix(trimmed, "//"))
		if !strings.HasPrefix(c, "Code generated by") {
			continue
		}
		return strings.Contains(c, "DO NOT EDIT.")
	}
	return false
}

// Find reports whether any scanned file contains the pattern, and names the first
// file that does.
//
// The file name is the evidence, because a reader who doubts the finding can open
// the line. The search is textual rather than AST-based for the tables where a name
// is a plain identifier, and that is stated rather than hidden: an AST walk is more
// precise and has to be taught every shape a reference can take, and the failure
// mode of a pattern that is too tight is a FALSE GREEN.
func (c *Corpus) Find(pattern string, excludePrefix ...string) (bool, string) {
	files := c.match(pattern, excludePrefix...)
	if len(files) == 0 {
		return false, ""
	}
	return true, files[0]
}

// FilesContaining lists the scanned files that contain the pattern.
func (c *Corpus) FilesContaining(pattern string, excludePrefix ...string) []string {
	return c.match(pattern, excludePrefix...)
}

func (c *Corpus) match(pattern string, excludePrefix ...string) []string {
	var out []string
	for _, rel := range c.files {
		skip := false
		for _, x := range excludePrefix {
			if strings.HasPrefix(rel, x) {
				skip = true
				break
			}
		}
		if skip {
			continue
		}
		if strings.Contains(c.byFile[rel], pattern) {
			out = append(out, rel)
		}
	}
	return out
}

// LineHits returns the scanned files with a non-comment line matching the pattern.
//
// Two things are stripped before the search, and both exist because a false green is the
// failure mode that does not get caught:
//
//   - Comment lines. A metric name in a doc comment is not a producer, and a capability
//     in a comment is not enforcement - this repository's own gates mention both in
//     comments constantly, and several of those comments exist precisely to RECORD that
//     something is not wired. Counting them would make a table report its own warnings as
//     coverage.
//   - Test files, via the corpus. A producer in a `_test.go` is not a producer.
//
// The pattern is a REGEXP, matched per line rather than across the whole file. A
// cross-file match would join two lines that are not adjacent and report a write that
// does not exist, which is the same false green in the other direction.
func (c *Corpus) LineHits(pattern string, excludePrefix ...string) []string {
	re, err := regexp.Compile(pattern)
	if err != nil {
		// A pattern this package wrote failing to compile is a bug here, and a gate
		// that silently treats it as "no matches" would report every declaration as
		// uncovered. Panicking names it in the first ten lines of output.
		panic("capability: bad pattern " + strconv.Quote(pattern) + ": " + err.Error())
	}
	var out []string
	for _, rel := range c.files {
		skip := false
		for _, x := range excludePrefix {
			if strings.HasPrefix(rel, x) {
				skip = true
				break
			}
		}
		if skip {
			continue
		}
		for _, line := range strings.Split(c.byFile[rel], "\n") {
			t := strings.TrimSpace(line)
			if strings.HasPrefix(t, "//") || strings.HasPrefix(t, "*") || strings.HasPrefix(t, "/*") {
				continue
			}
			if re.MatchString(line) {
				out = append(out, rel)
				break
			}
		}
	}
	return unique(out)
}

