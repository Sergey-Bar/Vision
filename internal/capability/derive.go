// 1. DispatchExecutors
// ---------------------------------------------------------------------------

// DeriveDispatchExecutors asserts that every type in the closed `rules.DispatchTypes`
// set has an executor registered in `internal/dispatch`.
//
// The registration is read from the source rather than from a registry call, because
// a registry call would make this table a statement that `internal/dispatch` agrees
// with itself: it would find exactly the executors the dispatcher chose to expose,
// and the closed set is the thing that must not grow without one. So the derivation
// reads the case labels of the executor switch, and the closed set is passed in as
// the vocabulary to check against it.
//
// The two sets being independent is the whole point. Before this table, the four
// keys were validated at bundle-compile time and consumed by exactly two call sites,
// both of which render text for `rules explain`.
func DeriveDispatchExecutors(root string, dispatchTypes map[string]bool) (Table, error) {
	t := Table{
		Name: "DispatchExecutors",
		Asserts: "every dispatch type a rule may request has an executor registered in " +
			"internal/dispatch. A type that parses, validates against the closed set, and is " +
			"then discarded is a rule an operator believes is running",
	}
	raw, err := os.ReadFile(filepath.Join(root, "internal", "dispatch", "dispatch.go"))
	if err != nil && !os.IsNotExist(err) {
		return t, err
	}
	registered := registeredExecutors(string(raw))
	for name := range dispatchTypes {
		item := Item{Name: name}
		if where, ok := registered[name]; ok {
			item.Covered = true
			item.Evidence = where
		} else {
			item.Evidence = "a case label in internal/dispatch's executorFor"
		}
		t.Items = append(t.Items, item)
	}
	sortItems(t.Items)
	return t, nil
}

// executorCase matches a case label in a switch on a dispatch type. The map-key form
// is accepted as well, because the executor registry could reasonably be either and
// a gate that only understood one would report a false green on the other.
// The registration is read from `internal/dispatch/dispatch.go`. Two shapes are accepted for
// a case label, because both are reasonable and a gate that understood only one would report
// a false green on the other:
//
//	dispatch.go:	case "notify_operator":
//	dispatch.go:	case TypeNotifyOperator:
//
// The second is a constant declared in the same file, so the gate resolves the identifier
// through that file's own constant block rather than guessing. That resolution is why this
// is not a hardcoded list of the four names: a list would need editing when a name changed,
// and a list nobody edited is a gate passing on a stale vocabulary.
//
// `executorFor` is the function whose cases count. The lookup accepts both a package-level
// `func executorFor` and a method - `func (d *Dispatcher) executorFor` - because the
// executor table became a method when the destinations moved behind a struct, and a gate
// pinned to one spelling reported four uncovered types against a working dispatcher. That
// is a false red on a tree whose side effects all work, which is the other direction of the
// same failure and just as misleading.
var (
	executorCaseLiteral = regexp.MustCompile(`case\s+"([a-z_]+)"\s*:`)
	executorCaseConst   = regexp.MustCompile(`case\s+([A-Z][A-Za-z0-9_]*)\s*:`)
	executorFuncDecl    = regexp.MustCompile(`func\s+(?:\([^)]*\)\s*)?(registeredExecutors|executorFor)\b`)
)

// constantDecl matches a file-local string constant declaration, e.g.
// `TypeNotifyOperator = "notify_operator"`.
var constantDecl = regexp.MustCompile(`(?m)^\s*([A-Z][A-Za-z0-9_]*)\s*=\s*"([a-z_]+)"`)

// registeredExecutors reads the labels in `internal/dispatch`'s executor switch.
func registeredExecutors(src string) map[string]string {
	out := map[string]string{}
	if strings.TrimSpace(src) == "" {
		return out
	}
	constants := map[string]string{}
	for _, m := range constantDecl.FindAllStringSubmatch(src, -1) {
		constants[m[1]] = m[2]
	}

	body := executorSwitchBody(src)
	for _, m := range executorCaseLiteral.FindAllStringSubmatch(body, -1) {
		out[m[1]] = "internal/dispatch executorFor case \"" + m[1] + "\""
	}
	for _, m := range executorCaseConst.FindAllStringSubmatch(body, -1) {
		value, known := constants[m[1]]
		if !known {
			// A label whose constant is not declared in this file. Recorded under its own
			// name so it appears in the table as an entry nothing matched, rather than
			// contributing nothing silently.
			out[m[1]] = "internal/dispatch executorFor case " + m[1] +
				" (constant not declared in that file)"
			continue
		}
		if _, already := out[value]; !already {
			out[value] = "internal/dispatch executorFor case " + m[1]
		}
	}
	return out
}

// executorSwitchBody is the text of `registeredExecutors`, from its `func` line to
// the closing brace at column zero.
//
// Found by name rather than by parsing, because the file is a package whose other
// declarations legitimately use the same literal syntax for different vocabularies,
// and a marker a human reads and updates is a smaller thing to get wrong than a
// heuristic. If the function is absent the whole file is returned, which
// over-reports rather than under-reports - and over-reporting here can only make the
// gate name something as covered that a reviewer then has to look at, which is the
// safe direction.
func executorSwitchBody(src string) string {
	at := executorFuncDecl.FindStringIndex(src)
	if at == nil {
		return src
	}
	if end := strings.Index(src[at[1]:], "\n}\n"); end > 0 {
		return src[at[1] : at[1]+end+2]
	}
	return src[at[1]:]
}

// ---------------------------------------------------------------------------
// 2. QueueEndpoints
// ---------------------------------------------------------------------------

// Queue is one work queue, as the declaring package spells it.
type Queue struct {
	// Name is the queue's stored value, e.g. `evidence_fetch`.
	Name string
	// Const is the Go constant, e.g. `QueueEvidenceFetch`.
	Const string
}

// DeriveQueueEndpoints asserts that every declared work queue has BOTH a producer
// and a worker.
//
// Both halves, because either alone is a queue that goes nowhere:
//
//   - A worker and no producer: the worker polls forever. That is
//     `QueueEvidenceFetch`, `QueueRuleBulk` and `QueueCheckpointSeal` today - three
//     constants in the vocabulary, three claim paths in `internal/jobs`, and nothing
//     anywhere that enqueues.
//   - A producer and no worker: work accumulates until a retention or alert threshold
//     fires on a backlog that will never drain.
//
// The two patterns cannot be satisfied by one occurrence in one file, because a
// producer is an `Enqueue` call naming the queue and a worker is a `jobs.Worker` whose
// `Name` is that queue. Both are matched on lines, so neither is satisfied by a name
// in a comment.
func DeriveQueueEndpoints(c *Corpus, queues []Queue) Table {
	t := Table{
		Name: "QueueEndpoints",
		Asserts: "every declared work queue has both a producer that enqueues into it and a " +
			"worker that drains it. A queue with only one of the two is work that accumulates " +
			"or a worker that polls an empty table",
	}
	for _, q := range queues {
		producers := c.LineHits(`Queue:\s*jobs\.` + q.Const + `\b`)
		workers := c.LineHits(`Name:\s*jobs\.` + q.Const + `\b`)
		item := Item{Name: q.Name}
		switch {
		case len(producers) > 0 && len(workers) > 0:
			item.Covered = true
			item.Evidence = "enqueued in " + joinFirst(producers) +
				", drained by a worker in " + joinFirst(workers)
		case len(producers) == 0 && len(workers) == 0:
			item.Evidence = "no enqueue caller and no worker registration"
		case len(producers) == 0:
			item.Evidence = "a worker in " + joinFirst(workers) + " and NO producer"
		default:
			item.Evidence = "enqueued in " + joinFirst(producers) + " and NO worker"
		}
		t.Items = append(t.Items, item)
	}
	sortItems(t.Items)
	return t
}

// ---------------------------------------------------------------------------
// 3. MetricProducers
// ---------------------------------------------------------------------------

// DeriveMetricProducers asserts that every metric name the registry declares is
// written by production code outside `internal/observability`.
//
// The input is the metric's Go CONSTANT (`CounterInboxAccepted`), not its exposition name
// (`inbox_accepted_total`). The exposition name is what a dashboard and an alert query
// use; the constant is what a call site writes. This derivation needs the one a call site
// can name, and the caller maps between them from the registry's own const block.
//
// `internal/observability` is excluded as a whole, not just its declaration file, because
// the registry renders a name on every scrape whether or not anything wrote it:
// `NewCounters` seeds every counter to zero and `Render` emits every gauge's zero value.
// That seeding is the right behaviour - a metric that appears only after something goes
// wrong is a metric nobody has a baseline for - and it is exactly why the registry cannot
// be its own evidence. A name nothing writes reads as `0` on every install, and a
// dashboard built on it reports a healthy site that never measured anything.
//
// The pattern requires the constant to be an ARGUMENT to something, so a name in a log
// field, a comparison or a doc table is not a producer.
//
// The argument is what the four write verbs have in common and it is looser than
// enumerating the verbs. An earlier version matched `Inc(observability.X)` and
// `.Set(observability.X)`, which missed the pipeline's own `l.inc(observability.X)` and
// `l.set(observability.X)` helpers - so it reported ten wired metrics as unwritten. A
// pattern that is too tight is a false green, which is the direction that does not get
// caught, so the looser correct rule wins over the tighter incomplete one.
func DeriveMetricProducers(c *Corpus, constants []string) Table {
	t := Table{
		Name: "MetricProducers",
		Asserts: "every declared metric is written by production code outside " +
			"internal/observability. A seeded counter reads as 0 on every install, so a " +
			"dashboard built on a name nothing writes reports a healthy site that never " +
			"measured anything",
	}
	for _, name := range constants {
		item := Item{Name: name}
		// The qualified form, which is how every call site names a registry constant.
		writers := c.LineHits(`observability\.` + regexp.QuoteMeta(name) + `\b`)
		if len(writers) == 0 {
			// The unqualified form, for a package that holds the constant in a local of
			// the same name - which is how the pipeline's `l.inc(...)` reads.
			writers = c.LineHits(`\b` + regexp.QuoteMeta(name) + `\b`)
		}
		if len(writers) > 0 {
			item.Covered = true
			item.Evidence = "written in " + joinFirst(writers)
		} else {
			item.Evidence = "a non-test write outside internal/observability"
		}
		t.Items = append(t.Items, item)
	}
	sortItems(t.Items)
	return t
}

// ---------------------------------------------------------------------------
// 4. CapabilityEnforcement
// ---------------------------------------------------------------------------

// DeriveCapabilityEnforcement asserts that every capability in the closed set is
// enforced by non-test code outside `internal/identity`.
//
// The input is the capability's Go CONSTANT (`CapIncidentRead`), not its wire value
// (`incident.read`), because the constant is what a route names. The caller maps one to
// the other by reading identity's declaration block - the same block
// `internal/identity/capability_coverage_test.go` reads, for the same stated reason:
// identity does not export the mapping and exporting it would be an API for a test.
//
// `internal/identity` is excluded because a declaration is not a use. Test files are
// excluded because a capability only a test has heard of is precisely the defect: a
// capability that grants nothing, on a role table that says it grants something.
//
// The search is a LINE search, not a whole-file one. A constant mentioned in a comment
// does not read as enforcement, and this repository's own gates mention capabilities in
// comments constantly - several of those comments exist precisely to record that a
// capability is NOT enforced, so counting them would make the table report its own
// warnings as coverage. That was a real false green, found by the fixture test.
func DeriveCapabilityEnforcement(c *Corpus, constants []string) Table {
	t := Table{
		Name: "CapabilityEnforcement",
		Asserts: "every declared capability is named by a route or a check in non-test code. " +
			"A capability nothing enforces grants nothing, and a role table listing it lies to " +
			"the auditor who reads it",
	}
	for _, name := range constants {
		item := Item{Name: name}
		readers := c.LineHits("identity."+name, "internal/identity/")
		if len(readers) > 0 {
			item.Covered = true
			item.Evidence = "named in " + joinFirst(readers)
		} else {
			item.Evidence = "a requireCapability or Authorize call outside internal/identity"
		}
		t.Items = append(t.Items, item)
	}
	sortItems(t.Items)
	return t
}

// ---------------------------------------------------------------------------
// 5. ContractRouting
// ---------------------------------------------------------------------------

// DeriveContractRouting asserts that the published contract and the router agree, in
// BOTH directions.
//
// One direction is the defect the plan names: operations declared in
// `contracts/openapi/v1/openapi.yaml` and implemented by nothing, so a client
// generated from the contract calls a 404. The other is worse for a reader and easier
// to miss: a route implemented and declared nowhere is a surface nobody can reach from
// the published description and nobody can discover exists.
//
// The console routes (`/incidents`, `/login`, `/coverage`, `/static/{file}`) are not
// in the contract and are not defects: they are HTML for a browser. They are excluded
// explicitly so "the console has no contract" does not read as an unexplained gap in
// this table's own output.
func DeriveContractRouting(root string) (Table, error) {
	t := Table{
		Name: "ContractRouting",
		Asserts: "every operation the OpenAPI document declares is registered on the mux, and " +
			"every /v1 route on the mux is declared. A declared route nothing implements is a " +
			"404 a generated client will hit; an implemented route no contract declares is a " +
			"surface nobody can reach from the published description",
	}
	declared, err := DeclaredOperations(filepath.Join(root, "contracts", "openapi", "v1", "openapi.yaml"))
	if err != nil {
		return t, err
	}
	routes, err := muxRoutes(root)
	if err != nil {
		return t, err
	}
	declaredSet := map[string]bool{}
	for _, op := range declared {
		declaredSet[canonicalOperation(op)] = true
	}
	implemented := map[string]bool{}
	for _, r := range routes {
		implemented[canonicalOperation(r)] = true
	}
	for _, op := range declared {
		item := Item{Name: op}
		if implemented[canonicalOperation(op)] {
			item.Covered = true
			item.Evidence = "registered on the mux"
		} else {
			item.Evidence = "a mux.Handle call in internal/api"
		}
		t.Items = append(t.Items, item)
	}
	for _, r := range routes {
		if !isJSONRoute(r) || declaredSet[canonicalOperation(r)] {
			continue
		}
		t.Items = append(t.Items, Item{
			Name:     r,
			Evidence: "a declaration in contracts/openapi/v1/openapi.yaml",
		})
	}
	sortItems(t.Items)
	return t, nil
}

// isJSONRoute reports whether an operation is on the JSON surface.
//
// The console routes (`/incidents`, `/login`, `/coverage`, `/static/{file}`) are HTML for
// a browser and are not in the contract, deliberately. Restricting this table's reverse
// direction to `/v1` is what keeps "the console has no contract" from reading as an
// unexplained gap in the table's own output.
func isJSONRoute(op string) bool {
	return strings.HasPrefix(op, "GET /v1/") || strings.HasPrefix(op, "POST /v1/") ||
		strings.HasPrefix(op, "PUT /v1/") || strings.HasPrefix(op, "DELETE /v1/") ||
		strings.HasPrefix(op, "PATCH /v1/")
}

// yamlPathOp and yamlMethod match a two-level OpenAPI mapping: a path at two spaces,
// a method at four.
//
// `tools/contractcheck` reads the same document with the same shape of reader, and
// reusing the shape is deliberate: two different notions of what an operation is is one
// of the ways a contract gate stops meaning anything.
var (
	yamlPathOp = regexp.MustCompile(`^  (/\S*):\s*$`)
	yamlMethod = regexp.MustCompile(`^    (get|post|put|delete|patch):\s*$`)
)

// muxRouteWithMethod and muxRouteNoMethod read the two registration forms.
//
// A METHOD-LESS pattern is matched too, and canonicalised to GET. `/v1/health` and
// `/v1/health/ready` are registered as `mux.HandleFunc("/v1/health", s.health)` with no
// method, which in Go's mux answers every method. Treating those as unregistered reported
// two operations as unimplemented on a tree where both work.
var (
	muxRouteWithMethod = regexp.MustCompile(`mux\.Handle(?:Func)?\("([A-Z]+) ([^"]+)"`)
	muxRouteNoMethod   = regexp.MustCompile(`mux\.Handle(?:Func)?\("(/[^"]*)"`)
)

// The queue patterns in DeriveQueueEndpoints tolerate the alignment gofmt inserts in a
// struct literal - `Queue: jobs.QueueVLM` and `Queue:          jobs.QueueVLM` are the same
// line - because a gate whose answer depends on how somebody aligned a field is answering
// a question about the source file rather than about the product.

// canonicalOperation replaces every path-template variable with `{}`.
//
// The document and the router NAME their variables differently - the contract says
// `{incidentId}` and the router says `{id}` - and a comparison that treats those as two
// different paths reports twelve operations as unimplemented on a tree where all twelve
// exist. The name of a path variable is not part of a route's identity; the SHAPE is.
//
// The original names are kept in the report, because a finding has to point at something
// a reader can open: the contract line for a declared operation, the mux line for an
// undeclared one.
func canonicalOperation(op string) string {
	method, path, found := strings.Cut(op, " ")
	if !found {
		return op
	}
	return method + " " + pathParam.ReplaceAllString(path, "{}")
}

// pathParam matches a path-template variable, `{id}` or `{incidentId}` alike.
var pathParam = regexp.MustCompile(`\{[^}]*\}`)

// DeclaredOperations reads the operations out of an OpenAPI document.
func DeclaredOperations(path string) ([]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read the OpenAPI document: %w", err)
	}
	var out []string
	current := ""
	for _, line := range strings.Split(string(raw), "\n") {
		if m := yamlPathOp.FindStringSubmatch(line); m != nil {
			current = m[1]
			continue
		}
		if current == "" {
			continue
		}
		if m := yamlMethod.FindStringSubmatch(line); m != nil {
			out = append(out, strings.ToUpper(m[1])+" "+current)
		}
	}
	sort.Strings(out)
	return out, nil
}

// muxRoutes reads the routes registered by internal/api.
//
// Both registration forms are read: the method-carrying one, and the method-less one that
// answers every method. The method-less form is canonicalised to GET for comparison
// against the document, and reported under the GET name so a reader can search for it.
func muxRoutes(root string) ([]string, error) {
	apiDir := filepath.Join(root, "internal", "api")
	entries, err := os.ReadDir(apiDir)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		raw, readErr := os.ReadFile(filepath.Join(apiDir, e.Name()))
		if readErr != nil {
			return nil, readErr
		}
		body := string(raw)
		for _, m := range muxRouteWithMethod.FindAllStringSubmatch(body, -1) {
			out = append(out, m[1]+" "+m[2])
		}
		for _, m := range muxRouteNoMethod.FindAllStringSubmatch(body, -1) {
			out = append(out, "GET "+m[1])
		}
	}
	sort.Strings(out)
	return out, nil
}

