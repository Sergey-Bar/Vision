func sortItems(items []Item) {
	sort.Slice(items, func(i, j int) bool { return items[i].Name < items[j].Name })
}

func unique(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, v := range in {
		if seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, v)
	}
	sort.Strings(out)
	return out
}

// joinFirst renders up to n file names, and says how many more there were.
//
// The count matters as much as the names: "written in internal/pipeline/pipeline.go and
// 1 more" tells a reader the evidence was found in more than one place, which is what a
// producer that has been wired twice looks like.
// joinFirst renders up to `mostShown` file names, and says how many more there were.
//
// The count matters as much as the names: "written in internal/pipeline/pipeline.go and
// 1 more" tells a reader the evidence was found in more than one place, which is what a
// maxEvidenceFiles is how many evidence files a message names before it counts the rest.
//
// Two, because a finding has to be actionable and "and 4 more" is not something a reader
// can act on by opening a file - it is a signal that the wiring is broad rather than a
// pointer. A constant rather than a literal at each call site so raising it is one edit.
const maxEvidenceFiles = 2

// joinFirst renders up to maxEvidenceFiles file names, and says how many more there were.
//
// The count matters as much as the names: "written in internal/pipeline/pipeline.go and
// 1 more" tells a reader the evidence was found in more than one place, which is what a
// producer that has been wired twice looks like.
func joinFirst(files []string) string {
	if len(files) == 0 {
		return "nowhere"
	}
	shown := files
	if len(shown) > maxEvidenceFiles {
		shown = shown[:maxEvidenceFiles]
	}
	out := strings.Join(shown, ", ")
	if len(files) > maxEvidenceFiles {
		out += fmt.Sprintf(" and %d more", len(files)-maxEvidenceFiles)
	}
	return out
}
