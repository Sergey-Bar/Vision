package qamatrix

import (
	"fmt"
	"sort"
	"strings"
)

// renderDoc generates `docs/qa-matrix.md` from the registry.
//
// The document is GENERATED and checked in, and the gate fails when the two
// disagree. The reason is the one `internal/statuscheck` applies to
// `docs/status.md`: a table a person reads and a table a machine checks are
// two truths unless one of them is produced from the other, and the version
// that gets read is the one nobody checks.
//
// The document says three things and stops:
//
//   - which package is in which tier
//   - which categories are covered by a named test, and which do not apply
//   - where the blanks are, and how many of them there are
//
// It does NOT claim the categories are covered. A category with a named test
// is a category with ONE test, and the `red-check` table is what proves the
// tests bite. A document that claimed otherwise would be a certificate rather
// than a checklist, and a certificate nobody can check is a decoration.
func renderDoc(reg *Registry, _ tree) string {
	var b strings.Builder

	b.WriteString("# The QA matrix\n\n")
	b.WriteString("<!-- GENERATED by internal/qamatrix from internal/qamatrix/registry.json.\n")
	b.WriteString("     Regenerate with: QAMATRIX_WRITE_DOCS=1 go test ./internal/qamatrix/...\n")
	b.WriteString("     Edit the registry, not this file. -->\n\n")

	if len(reg.Note) > 0 {
		for _, line := range reg.Note {
			b.WriteString(line)
			b.WriteString("\n")
		}
		b.WriteString("\n")
	}

	b.WriteString("## The fourteen categories\n\n")
	b.WriteString("The set is closed. A category outside it is a question nobody agreed to ask, ")
	b.WriteString("and a matrix whose categories are chosen per package is a matrix that only ")
	b.WriteString("says the package is fine.\n\n")
	for _, c := range closedCategories {
		b.WriteString("- `" + c + "`\n")
	}
	b.WriteString("\n")

	// The critical path first: it is the spine, and a reader who wants to
	// know what is proved about the product's chain should not have to hunt.
	b.WriteString("## The critical path\n\n")
	b.WriteString("Ten stages, closed. The chain is the one `AGENTS.md` protects and the one ")
	b.WriteString("the plan names: ingest, normalize, rule match, incident, attention queue, ")
	b.WriteString("operator read, disposition, audit ledger, checkpoint, replay.\n\n")
	b.WriteString("A stage that is dropped is a stage nobody is proving, and the omission is ")
	b.WriteString("invisible: the rest of the chain still passes. So the list lives in the code, ")
	b.WriteString("and the registry is checked against it.\n\n")
	b.WriteString("| Stage | Proved by |\n")
	b.WriteString("|---|---|\n")
	stages := map[string]Stage{}
	for _, s := range reg.CriticalPath {
		stages[s.Stage] = s
	}
	for _, want := range closedStages {
		proofs := "**MISSING**"
		if s, ok := stages[want]; ok {
			proofs = strings.Join(s.ProvedBy, "<br>")
		}
		b.WriteString("| " + want + " | " + proofs + " |\n")
	}
	b.WriteString("\n")

	// The tiers.
	for _, tier := range []string{"A", "B", "C"} {
		members := append([]string(nil), reg.Tiers[tier]...)
		sort.Strings(members)
		if len(members) == 0 {
			continue
		}
		b.WriteString("## Tier " + tier + "\n\n")
		b.WriteString(tierProse(tier))
		b.WriteString("\n\n")
		b.WriteString("| Package | Covered | Not applicable | Blank |\n")
		b.WriteString("|---|---|---|---|\n")
		for _, m := range members {
			row, ok := findRow(reg, m)
			if !ok {
				b.WriteString("| `" + m + "` | — | — | **NOT CLASSIFIED** |\n")
				continue
			}
			covered := []string{}
			na := []string{}
			blank := []string{}
			for _, c := range closedCategories {
				cat, present := row.Categories[c]
				switch {
				case !present || cat.blank():
					blank = append(blank, c)
				case strings.TrimSpace(cat.Reason) != "":
					na = append(na, c)
				default:
					covered = append(covered, c)
				}
			}
			b.WriteString("| `" + m + "` | " + cell(covered) + " | " + cell(na) + " | " + cell(blank) + " |\n")
		}
		b.WriteString("\n")
	}

	b.WriteString("## The blanks\n\n")
	total := blanks(reg)
	possible := len(reg.Packages) * len(closedCategories)
	fmt.Fprintf(&b, "%d of %d category slots are blank.\n\n", total, possible)
	b.WriteString("A blank is a category with no named test and no reason, and it is a ")
	b.WriteString("finding for a Tier A package. For a Tier B or C package it is allowed, ")
	b.WriteString("because the tier says how much coverage that package owes -- but it is ")
	b.WriteString("printed here and counted, because a gap that is invisible is a gap that ")
	b.WriteString("is never closed.\n\n")

	covered := 0
	na := 0
	for _, p := range reg.Packages {
		for _, c := range closedCategories {
			cat, present := p.Categories[c]
			switch {
			case !present || cat.blank():
			case strings.TrimSpace(cat.Reason) != "":
				na++
			default:
				covered++
			}
		}
	}
	fmt.Fprintf(&b, "Covered by a named test: %d. Not applicable, with a reason: %d. Blank: %d.\n",
		covered, na, total)
	b.WriteString("\n")
	b.WriteString("A category with a named test is a category with ONE test. It is not a proof ")
	b.WriteString("that the category is covered, and this document does not claim it is. ")
	b.WriteString("The `red-check` table is what proves the answers bite; this matrix is ")
	b.WriteString("what proves the answers are findable.\n")

	return b.String()
}

// tierProse says what a tier is for.
func tierProse(tier string) string {
	switch tier {
	case "A":
		return "The critical path and the things an operator is told will happen. Every " +
			"category is answered: a named test that exists, or a reason the category does " +
			"not apply. A blank here is a failure."
	case "B":
		return "The supporting machinery. A category may be blank, and the blank is counted " +
			"and printed. A reason is still better than nothing."
	case "C":
		return "The edges. A category may be blank, and the blank is counted and printed."
	default:
		return ""
	}
}

// cell renders a list of names for a Markdown table cell.
func cell(names []string) string {
	if len(names) == 0 {
		return "—"
	}
	quoted := make([]string, 0, len(names))
	for _, n := range names {
		quoted = append(quoted, "`"+n+"`")
	}
	return strings.Join(quoted, ", ")
}
