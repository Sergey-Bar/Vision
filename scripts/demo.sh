#!/bin/sh
# The demo, end to end, and a transcript of it.
#
# # What this is for
#
# A judge gets ninety seconds and a URL. Everything this script prints is a number
# the product measured, and the transcript it writes is the artefact a demo is
# judged on when the demo itself is gone.
#
# # Why it is a shell script and not a Go program
#
# Because it is a DRIVER, not a feature. Every claim it makes comes from running one
# of the product's own binaries and quoting what it printed; a Go driver would be a
# second implementation of the demo's logic, able to disagree with the thing it is
# demonstrating. A shell script that runs `securityctl acceptance` and captures its
# output cannot disagree with `securityctl acceptance`.
#
# # The rule it follows
#
# **Nothing here prints a number that did not come out of a command in this file.**
# Where a step could not run, the transcript says NOT RUN and names why. A
# transcript that reads well is worth less than one that is true, and a demo whose
# transcript was written by hand is a demo with no evidence at all.

set -eu

ROOT=${DEMO_ROOT:-/src}
OUT=${DEMO_OUT:-/src/dist/demo}
CORE=${DEMO_CORE_URL:-https://console:8443}
CACERT=${DEMO_CA:-/run/security-platform/console/console.crt}
mkdir -p "$OUT"
TRANSCRIPT="$OUT/transcript.md"

started=$(date -u +%Y-%m-%dT%H:%M:%SZ)

# step <n> <title> <command...>
#
# Runs the command, captures stdout+stderr and the exit code, and writes the pair
# into the transcript. The exit code is printed whatever it is: a step that fails is
# a finding about the product, and hiding it would make every other number in the
# transcript unfalsifiable.
step() {
    n="$1"; title="$2"; shift 2
    {
        printf '\n## %s. %s\n\n' "$n" "$title"
        printf '```\n$ %s\n' "$*"
    } >> "$TRANSCRIPT"
    set +e
    out=$("$@" 2>&1 | strip)
    code=$?
    set -e
    printf '%s\n' "$out" >> "$TRANSCRIPT"
    printf '```\n\nexit %s\n' "$code" >> "$TRANSCRIPT"
    printf '  [%s] exit %s\n' "$title" "$code"
}

# note <text>
#
# The text is in SINGLE quotes at every call site. In double quotes a backtick is
# command substitution, so the first version of this file -- which wrote
#
#	note "Criterion 02 is measured by `securityctl acceptance`."
#
# actually RAN the acceptance report and pasted its whole output into the middle of
# the transcript as if it were prose. The transcript was still true; it was just
# true twice and in the wrong place, which is the kind of thing that costs a reader
# more than it saves.
note() { printf '\n%s\n' "$1" >> "$TRANSCRIPT"; }

# strip writes a command's output to the transcript without its terminal control
# sequences.
#
# PowerShell colourises its output even when it is redirected, so the raw capture
# carried `\e[33;1m` into a markdown file. A transcript is read in a diff, and a
# diff full of escape sequences is a diff nobody reads.
strip() { sed -e 's/\x1b\[[0-9;]*m//g'; }

{
    printf '# Demo transcript\n\n'
    printf 'Generated by `scripts/demo.sh`. Every number below was printed by the command\n'
    printf 'shown above it, and nothing in this file was written by hand.\n\n'
    # `printf '%s\n'` rather than `printf '- ...'`: a format string that begins with
    # a dash is an OPTION to dash's builtin printf, and the first run of this script
    # died on it with "printf: Illegal option -", which names a shell status rather
    # than the line that caused it. There is no format string in this file that can
    # be read as an option.
    printf '%s\n' "- started: \`$started\`"
    printf '%s\n' "- console: \`$CORE\`"
    printf '%s\n' "- host: $(uname -s), $(uname -m)"
} > "$TRANSCRIPT"

printf 'demo: writing %s\n' "$TRANSCRIPT"

# ---------------------------------------------------------------------------
# 1. The gate. Nothing else in this transcript means anything until this one.
#
# Five of the twenty-five gates, not all of them, and the transcript says which five
# at the end so nobody reads the line "All gates passed" as a full run. The full
# run is `make verify-container` and it takes about forty minutes; a demo that
# blocked on it would be a demo nobody starts.
#
# The capture is the gate's OWN verdicts for those five. The grep names them rather
# than matching `==>`, because `==>` also matches the twenty lines saying a gate was
# NOT selected -- and a reader who sees twenty "not selected" lines above five "ok"
# lines has been handed the opposite of the point.
step 1 "the gate: five of twenty-five checks, run by this repository's own script" \
    sh -c 'cd "$1" && pwsh -NoProfile -File scripts/verify.ps1 \
        -Only contract-sync,migration-phases,generated-code,sql-guard,rules-lint \
        -NoRace -SkipRedCheck 2>&1 \
      | sed -e "s/\x1b\[[0-9;]*m//g" \
      | grep -E "^(==> (contract-sync|migration-phases|generated-code|sql-guard|rules-lint)$|    ok$|    FAILED|All gates passed)"' \
    sh "$ROOT"

# ---------------------------------------------------------------------------
# 2. The acceptance report. Thirteen criteria, three verdicts, `not-run` is
#    not `pass` and the report says so in words.
# ---------------------------------------------------------------------------
step 2 "the acceptance report: pass, fail, and not-run kept apart" \
    securityctl acceptance --soak 20

# ---------------------------------------------------------------------------
# 3. The capture path, against a real socket.
#
#    `serve-camera` is a CAMERA SUBSTITUTE and prints that it is one. This step is
#    the evidence that the whole capture path runs over TCP: a five-method
#    handshake, real SDP parsing, real RFC 6184, and the recovered NAL units
#    compared byte for byte with the source.
# ---------------------------------------------------------------------------
note 'Criterion 02 is measured by `securityctl acceptance`. This step shows the same capture path from the outside, so the two can be compared.'
CAMERA_LOG=/tmp/serve-camera.log
# `securityctl serve-camera`, not `serve-camera`. The first version of this script
# invoked it as a bare binary and got "serve-camera: not found" with exit 0, because
# a `sh -c` that fails inside a pipeline still exits zero and the transcript recorded
# the failure faithfully and unremarkably. Both are subcommands of one binary, which
# is why the compose demo service only has to build two.
securityctl serve-camera --listen 127.0.0.1:18554 --loop > "$CAMERA_LOG" 2>&1 &
camera_pid=$!
sleep 2
step 3 "a live RTSP server, and the capture path against it over TCP" \
    sh -c 'securityctl poc --camera rtsp://127.0.0.1:18554/live --max-time 6s 2>&1 | tail -20'
step 4 "what the server saw: the handshake, in order" \
    sh -c "cat $CAMERA_LOG"
kill "$camera_pid" 2>/dev/null || true
wait "$camera_pid" 2>/dev/null || true

# ---------------------------------------------------------------------------
# 5. Finding the second. A scripted vendor endpoint and the bookmark write.
# ---------------------------------------------------------------------------
note 'Criterion 09 is measured by `securityctl acceptance`. This step shows the endpoint itself.'
VMS_LOG=/tmp/serve-vms.log
securityctl serve-vms --listen 127.0.0.1:18000 --events 8 > "$VMS_LOG" 2>&1 &
vms_pid=$!
sleep 2
step 5 "a scripted vendor endpoint, serving the route table" \
    sh -c "cat $VMS_LOG"
step 6 "an adapter probe against it: every route, and what it could not say" \
    sh -c 'securityctl adapter-probe --base-url http://127.0.0.1:18000 2>&1 | head -30'
kill "$vms_pid" 2>/dev/null || true
wait "$vms_pid" 2>/dev/null || true

# ---------------------------------------------------------------------------
# 7. The console. Health, readiness, and the certificate's fingerprint, so a
#    judge who clicked through the browser warning can check what they accepted.
# ---------------------------------------------------------------------------
step 7 "the console's own health probe, trusting exactly the certificate the seed minted" \
    sh -c "securityctl healthcheck --url $CORE --ca $CACERT --timeout 5s"
step 8 "the console's readiness, which is the stricter question" \
    sh -c "securityctl healthcheck --url $CORE --ca $CACERT --ready --timeout 5s"

# ---------------------------------------------------------------------------
# 9. The seeded site. What is actually in the database a judge would be shown.
# ---------------------------------------------------------------------------
step 9 "the seeded site: what a judge is being shown, and what is behind it" \
    sh -c 'securityctl incidents list 2>&1 | head -30 || securityctl status 2>&1 | head -40'

# ---------------------------------------------------------------------------
# The footer. What this demo did NOT do, in the transcript itself rather than in
# a README nobody opens.
# ---------------------------------------------------------------------------
finished=$(date -u +%Y-%m-%dT%H:%M:%SZ)
{
    printf '\n---\n\n'
    printf '## What this demo did not do\n\n'
    printf '%s\n' '- **There is no camera, no VMS and no model behind any row above.** Every AI observation in the seeded site is either explicitly degraded with a named reason or labelled `seeded/absent`. A site where every observation is healthy would look better and prove nothing about the invariant that matters.'
    printf '%s\n' '- The RTSP server is a **camera substitute**. It answers a real handshake and streams real H.264, and it does not decide how to encode, when to send a keyframe, or how it behaves on a lossy network.'
    printf '%s\n' '- The vendor endpoint is **scripted**, not a Milestone installation. It serves the route table and it holds no recording.'
    printf '%s\n' '- Step 1 runs FIVE of the twenty-five gates — contract-sync, migration-phases, generated-code, sql-guard and rules-lint — and says so. A full run is `make verify-container`, and this transcript does not stand in for it.'
    printf '%s\n' '- Criteria 06, 07, 08 and 10 are reported `NOT RUN` by the acceptance report, and `NOT RUN` is a distinct verdict from `pass` on purpose.'
    printf '\nfinished: `%s`\n' "$finished"
} >> "$TRANSCRIPT"

printf 'demo: wrote %s\n' "$TRANSCRIPT"