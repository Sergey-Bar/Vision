// site-config — the autonomous configurator's operator surface.
//
// Three subcommands, one artifact: `generate` emits the artifact from what the
// site declares and what it has learned; `plan` prints the desired-vs-actual
// diff; `apply` writes it. The command is idempotent, so after activation
// autonomy is a schedule (a systemd timer or Task Scheduler job) rather than a
// daemon — nothing new runs in the product process.
//
// The apply target here is the POC's file target: the artifact directory this
// CLI itself regenerates. The Milestone target is the product's, behind the
// same `siteconfig.Target` interface, which is the multi-VMS seam; nothing
// below it changes when that target lands. Every write the VMS target would
// make goes through routes that are all still Unverified, so a real
// configuration change waits on a human probe the milestone-probe skill
// governs.
func siteConfigCommand() *command.Command {
	c := &command.Command{
		Name:    "site-config",
		Summary: "Generate, plan and apply a site's configuration from declarations and measurements",
		Usage: `site-config — the autonomous configurator.

  site-config generate --site <yaml> --registry <yaml> --out <dir> [--observations <jsonl>] [--headroom <jsonl>]
  site-config plan     --site <yaml> --registry <yaml> --dir <dir>
  site-config apply    --site <yaml> --registry <yaml> --dir <dir> [--yes] [--max-changes <n>]

The artifact every subcommand works from is one YAML file with provenance on
every entry: declared (a human wrote it), learned (the pipeline's facts
produced it, with its evidence) or assumed (nobody knows and the artifact says
so). Two runs over the same facts produce the same bytes.

plan is the default state of apply: without --yes, apply prints the plan and
changes nothing. Every change is recorded, an unknown target shape refuses the
whole plan, retention is extend-only, and nothing is ever deleted.`,
	}
	c.Children = []*command.Command{
		siteConfigGenerateCommand(),
		siteConfigPlanCommand(),
		siteConfigApplyCommand(),
	}
	return c
}

// siteConfigOptions are the flags the three subcommands share, so a plan and
// the apply that follows it cannot be computed from different inputs.
type siteConfigOptions struct {
	siteFile     string
	registryFile string
	dir          string
	observations string
	headroom     string
	out          string
	yes          bool
	maxChanges   int
}

func registerSiteConfigFlags(fs *flag.FlagSet, o *siteConfigOptions, forApply bool) {
	fs.StringVar(&o.siteFile, "site", "", "Site model YAML: cameras, zones and routes.")
	fs.StringVar(&o.registryFile, "registry", "", "Camera registry YAML: id, name, stream URL.")
	fs.StringVar(&o.observations, "observations", "", "Optional JSONL of measured occupancy, one observation per line.")
	if forApply {
		fs.StringVar(&o.dir, "dir", "", "The artifact directory to reconcile against.")
		fs.BoolVar(&o.yes, "yes", false, "Actually write. Without it, apply prints the plan and changes nothing.")
		fs.IntVar(&o.maxChanges, "max-changes", 20, "Per-hour change cap. A larger plan is refused whole.")
	} else {
		fs.StringVar(&o.out, "out", "", "Directory the artifact is written to.")
	}
}

func siteConfigGenerateCommand() *command.Command {
	var o siteConfigOptions
	c := &command.Command{
		Name:    "generate",
		Summary: "Write the provenance-carrying site artifact",
		Usage: `generate --site <yaml> --registry <yaml> --out <dir>

Emits one artifact YAML: every camera and zone with its origin and evidence, a
learned-zone proposal per camera that dwelled somewhere, and a capture/retention
plan per camera derived from the measured headroom. The same inputs produce the
same bytes, every run.`,
	}
	c.Flags = func(fs *flag.FlagSet) {
		registerSiteConfigFlags(fs, &o, false)
	}
	c.Run = func(ctx context.Context, env *command.Env, args []string) error {
		if len(args) > 0 {
			return &command.UsageError{Err: errors.New("pass options as flags, not positionals")}
		}
		if o.siteFile == "" || o.registryFile == "" || o.out == "" {
			return &command.UsageError{Err: errors.New("--site, --registry and --out are all required")}
		}
		art, routes, err := buildArtifact(o)
		if err != nil {
			return err
		}
		if err := os.MkdirAll(o.out, 0o750); err != nil {
			return fmt.Errorf("create the artifact directory: %w", err)
		}
		path := filepath.Join(o.out, "artifact.yaml")
		data, err := yaml.Marshal(art)
		if err != nil {
			return fmt.Errorf("marshal the artifact: %w", err)
		}
		header := fmt.Sprintf("# Generated by `securityctl site-config generate`. Digested as %s.\n"+
			"# Every entry carries its origin: declared | learned | assumed, with its evidence.\n", art.Digest())
		if err := os.WriteFile(path, append([]byte(header), data...), 0o600); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
		fmt.Fprint(env.Stdout, art.Summary())
		fmt.Fprintf(env.Stdout, "capture ceiling: %.1f fps (measured headroom decides below it, floor %.2f, default %.2f)\n",
			siteconfig.MaxCaptureFPS, siteconfig.MinCaptureFPS, siteconfig.DefaultCaptureFPS)
		fmt.Fprint(env.Stdout, zoneTypeLine(art))
		// The analytics derivation, in the shape anomaly.DefaultRuleSet uses:
		// a human reads it before it becomes a bundle candidate, and the
		// bundle is activated by a human after that.
		rules := siteconfig.AnalyticsRules(art.Zones, routes)
		if len(rules) > 0 {
			fmt.Fprintf(env.Stdout, "derived rules: %d\n", len(rules))
			for _, r := range rules {
				fmt.Fprintf(env.Stdout, "  %-16s %-8s %-22s %s\n", r.ZoneID, r.Type, r.Threshold, r.MinSeverity)
			}
		}
		fmt.Fprintf(env.Stdout, "written: %s\n", path)
		return nil
	}
	return c
}

// zoneTypeLine counts the artifact's zones by type, using the same vocabulary
// the site model does rather than a second one.
func zoneTypeLine(art *siteconfig.Artifact) string {
	counts := map[string]int{}
	for _, z := range art.Zones {
		counts[z.Type]++
	}
	types := []string{
		siteconfig.ZoneTypeRestricted,
		siteconfig.ZoneTypeChoke,
		siteconfig.ZoneTypeMonitor,
		siteconfig.ZoneTypeAsset,
		siteconfig.ZoneTypeRoute,
	}
	var parts []string
	for _, t := range types {
		if n := counts[t]; n > 0 {
			parts = append(parts, fmt.Sprintf("%s %d", t, n))
		}
	}
	if len(parts) == 0 {
		return "zones by type: none\n"
	}
	return "zones by type: " + strings.Join(parts, ", ") + "\n"
}

func siteConfigPlanCommand() *command.Command {
	var o siteConfigOptions
	c := &command.Command{
		Name:    "plan",
		Summary: "Print the desired-vs-actual diff for the artifact directory",
		Usage:   `plan --site <yaml> --registry <yaml> --dir <dir>`,
	}
	c.Flags = func(fs *flag.FlagSet) {
		o.maxChanges = 20
		fs.StringVar(&o.siteFile, "site", "", "Site model YAML.")
		fs.StringVar(&o.registryFile, "registry", "", "Camera registry YAML.")
		fs.StringVar(&o.dir, "dir", "", "The artifact directory to reconcile against.")
	}
	c.Run = func(ctx context.Context, env *command.Env, args []string) error {
		if len(args) > 0 {
			return &command.UsageError{Err: errors.New("pass options as flags, not positionals")}
		}
		if o.siteFile == "" || o.registryFile == "" || o.dir == "" {
			return &command.UsageError{Err: errors.New("--site, --registry and --dir are all required")}
		}
		art, target, desired, err := buildDesired(o)
		if err != nil {
			return err
		}
		actual, err := target.List(ctx)
		if err != nil {
			return err
		}
		plan := siteconfig.PlanWithDesired(siteconfig.Reconcile(desired, actual), desired)
		fmt.Fprintf(env.Stdout, "artifact %s (%s)\n\n", o.dir, art.Digest())
		fmt.Fprint(env.Stdout, plan.Summary())
		return nil
	}
	return c
}

func siteConfigApplyCommand() *command.Command {
	var o siteConfigOptions
	c := &command.Command{
		Name:    "apply",
		Summary: "Reconcile the artifact directory, recording every change",
		Usage: `apply --site <yaml> --registry <yaml> --dir <dir> [--yes] [--max-changes <n>]

The dry run is the default: without --yes this prints the plan and writes
nothing. With it, the pre-apply state is snapshotted to the artifact directory,
each change is written idempotently and recorded, an unknown shape refuses the
whole plan, an object this engine did not create is adopted and left alone, a
retention reduction is refused, and nothing is ever deleted.`,
	}
	c.Flags = func(fs *flag.FlagSet) {
		registerSiteConfigFlags(fs, &o, true)
	}
	c.Run = func(ctx context.Context, env *command.Env, args []string) error {
		if len(args) > 0 {
			return &command.UsageError{Err: errors.New("pass options as flags, not positionals")}
		}
		if o.siteFile == "" || o.registryFile == "" || o.dir == "" {
			return &command.UsageError{Err: errors.New("--site, --registry and --dir are all required")}
		}
		art, target, desired, err := buildDesired(o)
		if err != nil {
			return err
		}
		actual, err := target.List(ctx)
		if err != nil {
			return err
		}
		plan := siteconfig.PlanWithDesired(siteconfig.Reconcile(desired, actual), desired)

		sink := &stdoutSink{out: env.Stdout}
		snapshot := func(objects []siteconfig.Object) error {
			return writeSnapshot(o.dir, objects)
		}
		report, err := siteconfig.Apply(ctx, target, plan, sink, siteconfig.ApplyOptions{
			DryRun:            !o.yes,
			MaxChangesPerHour: o.maxChanges,
			Snapshot:          snapshot,
			// The objects were read above to compute the plan; Apply does not read
			// them a second time. A list is a paginated vendor call, and two reads
			// that can see different states is two answers to one question.
			Actual: actual,
		})
		if err != nil {
			return err
		}
		if !o.yes {
			fmt.Fprintf(env.Stdout, "\ndry run: %d changes would be written; pass --yes to apply.\n", len(plan.Appliable()))
			return nil
		}
		fmt.Fprintf(env.Stdout, "\napplied %d changes to %s (artifact %s).\n", len(report.Applied), o.dir, art.Digest())
		return nil
	}
	return c
}

// buildArtifact assembles the artifact the three subcommands share, plus the
// declared route ids its analytics derivation flows into. It is the same inputs
// every time, which is what makes a plan and its apply agree.
func buildArtifact(o siteConfigOptions) (*siteconfig.Artifact, []string, error) {
	site, err := sitemodel.LoadFromFile(o.siteFile)
	if err != nil {
		return nil, nil, fmt.Errorf("load the site model: %w", err)
	}
	registry, err := loadRegistry(o.registryFile)
	if err != nil {
		return nil, nil, err
	}
	observations, err := loadObservations(o.observations)
	if err != nil {
		return nil, nil, err
	}
	headroom, err := loadHeadroom(o.headroom)
	if err != nil {
		return nil, nil, err
	}
	declared := make([]siteconfig.Zone, 0, len(site.Zones))
	for _, z := range site.Zones {
		declared = append(declared, siteconfig.Zone{
			ID:      z.ID,
			Type:    z.Type,
			Polygon: toPoints(z.Polygon),
			Cameras: camerasForZone(site, z.ID),
			Prov:    siteconfig.Provenance{Origin: siteconfig.OriginDeclared, Evidence: "the site model: " + o.siteFile},
		})
	}
	routes := make([]string, 0, len(site.Routes))
	for _, r := range site.Routes {
		routes = append(routes, r.ID)
	}
	in := siteconfig.GenerateInput{
		SiteID:        site.ID,
		GeneratedAt:   time.Now().UTC(),
		Inventory:     registry,
		DeclaredZones: declared,
		Observations:  observations,
		LearnCfg:      siteconfig.DefaultLearnConfig(),
		Headroom:      headroom,
	}
	art, err := siteconfig.Generate(in)
	if err != nil {
		return nil, nil, err
	}
	return art, routes, nil
}

// buildDesired is the artifact plus the target plus the desired objects a
// reconcile compares. Both plan and apply call it, from the same inputs.
func buildDesired(o siteConfigOptions) (*siteconfig.Artifact, siteconfig.Target, []siteconfig.Object, error) {
	art, _, err := buildArtifact(o)
	if err != nil {
		return nil, nil, nil, err
	}
	desired := artifactObjects(art)
	if err := validateObjects(desired); err != nil {
		return nil, nil, nil, err
	}
	return art, siteconfig.NewFileTarget(o.dir), desired, nil
}

func artifactObjects(art *siteconfig.Artifact) []siteconfig.Object {
	out := make([]siteconfig.Object, 0, len(art.Cameras)+len(art.Zones)+len(art.Video))
	for _, c := range art.Cameras {
		vals := map[string]string{"name": c.Name}
		if c.Position != nil {
			vals["position"] = fmt.Sprintf("%.0f,%.0f", c.Position.X, c.Position.Y)
		}
		out = append(out, siteconfig.Object{
			Kind: siteconfig.KindCamera, ID: c.ID, Shape: siteconfig.KindCamera,
			Fingerprint: fingerprint("camera", c.ID, c.Name, c.Prov.Origin), Values: vals,
		})
	}
	for _, z := range art.Zones {
		out = append(out, siteconfig.Object{
			Kind: siteconfig.KindZone, ID: z.ID, Shape: siteconfig.KindZone,
			Fingerprint: fingerprint("zone", z.ID, z.Type, fmt.Sprint(z.Polygon), z.Prov.Origin),
			Values:      map[string]string{"type": z.Type, "cameras": strings.Join(z.Cameras, "+")},
		})
	}
	for _, v := range art.Video {
		out = append(out, siteconfig.Object{
			Kind: siteconfig.KindVideo, ID: v.CameraID, Shape: siteconfig.KindVideo,
			Fingerprint:   fingerprint("video", v.CameraID, fmt.Sprint(v.CaptureFPS), fmt.Sprint(v.RetentionDays), v.Prov.Origin),
			RetentionDays: v.RetentionDays,
			Values:        map[string]string{"fps": fmt.Sprint(v.CaptureFPS), "retention_days": fmt.Sprint(v.RetentionDays)},
		})
	}
	return out
}

func fingerprint(parts ...string) string {
	return strings.Join(parts, "/")
}

// validateObjects refuses to plan over an object the engine cannot write,
// before a target is ever touched: a plan containing an unknown shape is
// refused whole.
func validateObjects(objs []siteconfig.Object) error {
	for _, o := range objs {
		if err := o.Validate(); err != nil {
			return err
		}
	}
	return nil
}

// loadRegistry reads the camera registry: a static inventory, which is what a
// declared registry is. An unknown position is left unknown, and the artifact
// marks it assumed rather than guessing a coordinate.
func loadRegistry(path string) (siteconfig.StaticInventory, error) {
	var doc struct {
		Cameras []struct {
			ID         string   `yaml:"id"`
			Name       string   `yaml:"name"`
			YouTubeURL string   `yaml:"youtube_url"`
			ZoneIDs    []string `yaml:"zone_ids"`
		} `yaml:"cameras"`
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read the camera registry: %w", err)
	}
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("parse the camera registry: %w", err)
	}
	if len(doc.Cameras) == 0 {
		return nil, errors.New("the camera registry names no cameras")
	}
	out := make(siteconfig.StaticInventory, 0, len(doc.Cameras))
	for _, c := range doc.Cameras {
		out = append(out, siteconfig.Camera{
			ID:        c.ID,
			Name:      c.Name,
			ZoneHints: c.ZoneIDs,
			Prov: siteconfig.Provenance{
				Origin:   siteconfig.OriginDeclared,
				Evidence: "the camera registry: " + path,
			},
		})
	}
	return out, nil
}

// loadObservations reads the occupancy the pipeline measured, if it was
// measured. A missing file is not an error: a site with no learned zones is a
// site whose observations were never taken, and the artifact says so by
// omission rather than failing.
func loadObservations(path string) ([]siteconfig.Observation, error) {
	return readJSONL(path, func(line []byte) (siteconfig.Observation, bool, error) {
		var o siteconfig.Observation
		if err := json.Unmarshal(line, &o); err != nil {
			return o, false, err
		}
		return o, o.CameraID != "", nil
	})
}

func loadHeadroom(path string) ([]siteconfig.CameraHeadroom, error) {
	return readJSONL(path, func(line []byte) (siteconfig.CameraHeadroom, bool, error) {
		var o siteconfig.CameraHeadroom
		if err := json.Unmarshal(line, &o); err != nil {
			return o, false, err
		}
		return o, o.CameraID != "", nil
	})
}

func readJSONL[T any](path string, decode func(line []byte) (T, bool, error)) ([]T, error) {
	if path == "" {
		return nil, nil
	}
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return nil, fmt.Errorf("%s: no such file", path)
		}
		return nil, fmt.Errorf("open %s: %w", path, err)
	}
	defer func() { _ = f.Close() }()
	var out []T
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)
	n := 0
	for sc.Scan() {
		n++
		line := sc.Bytes()
		if len(line) == 0 {
			continue
		}
		item, keep, err := decode(line)
		if err != nil {
			return nil, fmt.Errorf("%s line %d: %w", path, n, err)
		}
		if keep {
			out = append(out, item)
		}
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("read %s: %w", path, err)
	}
	return out, nil
}

func toPoints(in []sitemodel.Point) []siteconfig.Point {
	out := make([]siteconfig.Point, 0, len(in))
	for _, p := range in {
		out = append(out, siteconfig.Point{X: p.X, Y: p.Y})
	}
	return out
}

// camerasForZone is the site model's declaration, read through the one
// accessor that owns it (see sitemodel.Site.CamerasForZone).
func camerasForZone(site *sitemodel.Site, zoneID string) []string {
	return site.CamerasForZone(zoneID)
}

// stdoutSink records every applied change to the operator's terminal. It is a
// real sink for the CLI: the record of what changed is written here and the
// snapshot is written to the artifact directory, so a change is visible to the
// person who ran the command.
type stdoutSink struct {
	out interface{ Write([]byte) (int, error) }
}

func (s *stdoutSink) RecordChange(kind, objectKind, objectID, reason string) error {
	if s.out == nil {
		return nil
	}
	_, err := fmt.Fprintf(s.out, "recorded %s %s %s: %s\n", kind, objectKind, objectID, reason)
	return err
}

// writeSnapshot is the pre-apply evidence: the target's current objects, under
// the artifact directory's own `snapshots/`, so a restore is an operator
// procedure over a file rather than a rollback system this tool has to get
// right. The subdirectory matters: List reads only the artifact directory's
// top level, and a snapshot sitting beside the objects it captured would be
// read back as one of them — and then refused for having an unknown shape,
// which would make the second run of an idempotent command fail.
func writeSnapshot(dir string, objects []siteconfig.Object) error {
	data, err := yaml.Marshal(map[string]any{
		"taken_at": time.Now().UTC().Format(time.RFC3339),
		"objects":  objects,
	})
	if err != nil {
		return err
	}
	snapDir := filepath.Join(dir, "snapshots")
	if err := os.MkdirAll(snapDir, 0o750); err != nil {
		return err
	}
	name := filepath.Join(snapDir, "snapshot-"+time.Now().UTC().Format("20060102T150405")+".yaml")
	return os.WriteFile(name, data, 0o600)
}
